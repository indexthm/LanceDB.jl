# Generate reference bindings from the header shipped in the JLL artifact.
# Run: julia --project=gen gen/generator.jl
#
# src/api.jl and ctypes.jl are maintained manually; do not overwrite them.
# Arrow C ABI struct layouts defined in src/arrow_abi.jl are NOT generated —
# they are maintained manually to match the Arrow C Data Interface spec.

using Clang.Generators
using LanceDB_C_jll

HEADER = joinpath(LanceDB_C_jll.artifact_dir, "include", "lancedb.h")

OUTPUT = joinpath(@__DIR__, "bindings.generated.jl")

mktemp() do preamble, io
    # The shipped C header omits this typedef for its forward-declared struct.
    write(io, "typedef struct LanceDBObjectStoreRegistry LanceDBObjectStoreRegistry;\n")
    close(io)
    args = get_default_args()
    append!(args, ["-x", "c", "-include", preamble])
    options = Dict{String,Any}("general" => Dict{String,Any}(
        "library_name" => "liblancedb",
        "output_file_path" => OUTPUT,
    ))
    ctx  = create_context([HEADER], args, options)
    build!(ctx)
end

# Prepend the required constant reference and auto-gen header
lines = readlines(OUTPUT)
header = """
# AUTO-GENERATED by gen/generator.jl — do not edit by hand.
# Regenerate with: julia --project=gen gen/generator.jl
# Reference only: review signatures and ownership before updating src/.

"""
write(OUTPUT, header * join(lines, "\n"))
println("Generated: $OUTPUT")
